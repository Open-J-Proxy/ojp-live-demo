\set ON_ERROR_STOP on
BEGIN;
CREATE TABLE IF NOT EXISTS users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username varchar(255) NOT NULL UNIQUE,
    email varchar(255) NOT NULL UNIQUE,
    created_at timestamp NOT NULL
);
CREATE TABLE IF NOT EXISTS products (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255) NOT NULL,
    price numeric(38,2) NOT NULL CHECK (price > 0)
);
CREATE TABLE IF NOT EXISTS orders (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id),
    order_date timestamp NOT NULL
);
CREATE TABLE IF NOT EXISTS order_items (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    product_id bigint NOT NULL REFERENCES products(id),
    quantity integer NOT NULL CHECK (quantity BETWEEN 1 AND 20)
);
CREATE TABLE IF NOT EXISTS reviews (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id),
    product_id bigint NOT NULL REFERENCES products(id),
    rating integer NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment text NOT NULL
);
CREATE INDEX IF NOT EXISTS orders_user_date ON orders(user_id, order_date DESC);
CREATE INDEX IF NOT EXISTS orders_date ON orders(order_date);
CREATE INDEX IF NOT EXISTS items_order ON order_items(order_id);
CREATE INDEX IF NOT EXISTS items_product ON order_items(product_id);
CREATE INDEX IF NOT EXISTS reviews_product ON reviews(product_id);
CREATE INDEX IF NOT EXISTS reviews_user ON reviews(user_id);
CREATE INDEX IF NOT EXISTS products_price ON products(price);
CREATE TABLE IF NOT EXISTS benchmark_seed (
    singleton boolean PRIMARY KEY DEFAULT true CHECK (singleton),
    seed bigint NOT NULL,
    users bigint NOT NULL,
    products bigint NOT NULL,
    orders bigint NOT NULL,
    items bigint NOT NULL,
    reviews bigint NOT NULL
);
CREATE OR REPLACE FUNCTION benchmark_reset() RETURNS void LANGUAGE plpgsql AS $$
DECLARE b benchmark_seed%ROWTYPE;
BEGIN
    SELECT * INTO STRICT b FROM benchmark_seed;
    DELETE FROM reviews WHERE id > b.reviews;
    DELETE FROM orders WHERE id > b.orders;
    PERFORM setval(pg_get_serial_sequence('orders', 'id'), b.orders, true);
    PERFORM setval(pg_get_serial_sequence('order_items', 'id'), b.items, true);
    PERFORM setval(pg_get_serial_sequence('reviews', 'id'), b.reviews, true);
END $$;
COMMIT;
